"use strict";
const assert = require("node:assert/strict"), { merge } = require("../src/domain/shiny-history");
const history = [{ p: 0, n: "Ancient_Abra", t: 10, cap: 1, acc: "Legacy" }];
assert.equal(merge(history, [{ n: "Ancient Abra", t: 10, cap: 1, iv: 180, q: 1 }], 0, "first", "Legacy"), true);
assert.equal(history.length, 1, "legacy logs and capture backfill represent the same event");
assert.equal(history[0].iv, 180);
assert.equal(merge(history, [{ n: "Ancient Abra", t: 10, cap: 1 }], 0, "first", "Legacy"), false);
merge(history, [{ n: "Ancient Abra", t: 10, cap: 1 }], 1, "second", "Other");
assert.equal(history.length, 2, "simultaneous events from different accounts remain separate");
merge(history, [{ n: "Abra", t: 20, def: 1 }], 0, "first", "Legacy");
assert.equal(history.filter(x => x.cap).length, 2);
assert.equal(history.filter(x => x.def).length, 1);
const reopened = JSON.parse(JSON.stringify(history));
assert.equal(merge(reopened, [{ n: "Abra", t: 20, def: 1 }], 0, "first", "Legacy"), false, "reopening does not duplicate the lifetime history");
for (let i = 0; i < 20; i++) merge(reopened, [{ n: "Abra", t: 100 + i, cap: 1 }], 0, "first", "Legacy");
assert.equal(reopened.filter(x => x.cap).length, 22, "history has no twelve-capture display limit");
let savedLifetime = 2837;
const increase = () => savedLifetime++;
merge(reopened, [{ n: "New shiny", t: 1000, def: 1 }], 0, "first", "Legacy", increase);
merge(reopened, [{ n: "New shiny", t: 1000, def: 1 }], 0, "first", "Legacy", increase);
assert.equal(savedLifetime, 2838, "the existing lifetime total increments once for a new encounter");
console.log("Shiny history: legacy recovery, enrichment, deduplication, account isolation and persistence passed.");
