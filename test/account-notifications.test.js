'use strict';
const assert = require('node:assert/strict');
const { create } = require('../src/domain/account-notifications');
const summary = require('../src/renderer/summary');
let saved;
const notices = create({}, value => { saved = JSON.parse(JSON.stringify(value)); });
const state = (cid = 'one', epoch = 'hunt1', captures = [], drops = []) => ({ ok: true, live: true, cid, a: { epoch }, captures, drops });
const important = entry => summary.important(entry);
const old = { id: 'old', t: 1, n: 'Dratini', iv: 190 };
notices.observe(state('one', 'hunt1', [old], [{ name: 'Boss Token', qty: 30 }]), important);
assert.equal(notices.unread('one'), 0, 'initial observation does not replay historical captures or loot');
const captures = [old, { id: 'new', t: 2, n: 'Pupitar', iv: 171 }, { id: 'shiny', t: 3, n: 'Abra', sh: 1, iv: 10 }, { id: 'common', t: 4, n: 'Gastly', iv: 20 }];
const drops = [{ name: 'Boss Token', qty: 32 }, { name: 'Strange Pheromone', qty: 1 }, { name: 'Enchanted Gem', qty: 500 }];
notices.observe(state('one', 'hunt1', captures, drops), important);
assert.equal(notices.unread('one'), 4, 'important capture, shiny and each requested rare item notify');
assert.equal(notices.entries('one').find(x => x.name === 'Boss Token').quantity, 2);
notices.observe(state('one', 'hunt1', captures, drops), important);
assert.equal(notices.unread('one'), 4, 'repeated polling does not duplicate notifications');
notices.observe(state('two', 'hunt1', [], []), important);
notices.observe(state('two', 'hunt1', [captures[1]], [{ name: 'boss token', qty: 1 }]), important);
assert.equal(notices.unread('two'), 2, 'accounts have independent capture and drop tracking');
notices.markRead('one');
assert.equal(notices.unread('one'), 0);
assert.equal(notices.unread('two'), 2, 'reading one account preserves the other badge');
const restored = create(saved);
assert.equal(restored.unread('one'), 0);
assert.equal(restored.unread('two'), 2, 'read and unread history survives restart');
notices.observe(state('one', 'hunt1', captures, [{ name: 'Boss Token', qty: 1 }]), important);
assert.equal(notices.unread('one'), 0, 'decreasing counters do not produce fake loot');
notices.observe(state('one', 'hunt2', captures, [{ name: 'Boss Token', qty: 1 }]), important);
assert.equal(notices.unread('one'), 1, 'first rare drop in a new hunt is counted');
notices.observe({ ...state('one', 'hunt2', captures, [{ name: 'Boss Token', qty: 2 }]), live: false }, important);
assert.equal(notices.unread('one'), 1, 'offline snapshots do not notify');
notices.observe(state('one', 'hunt2', captures, [{ name: 'Boss Token', qty: 2 }]), important);
assert.equal(notices.unread('one'), 2, 'reconnection observes only new loot');
notices.observe(state('one', 'hunt2', captures, [{ name: 'Boss Token', qty: 3 }]), important, ['Other item']);
assert.equal(notices.unread('one'), 2, 'configured item names replace defaults');
const session = require('../src/game/session');
const game = session.createState(100);
game.api['/api/characters/me'] = { character: { id: 'real-event' } };
game.api['/game/items.json'] = { items: [{ id: 7, name: 'Boss Token', npcPrice: 1 }] };
game.sock = { readyState: 1 };
session.reduce(game, { type: 'field-init', slug: 'hunt' }, 100);
notices.observe(session.snapshot(game, 100), important);
session.reduce(game, { type: 'field-kill', loot: [{ itemId: 7, qty: 2 }] }, 200);
notices.observe(session.snapshot(game, 200), important);
assert.equal(notices.unread('real-event'), 1, 'catalog resolves rare loot when native events only include an item ID');
assert.equal(notices.entries('real-event')[0].quantity, 2);
console.log('Account notifications: baseline, captures, shiny, rare loot deltas, duplicates, hunt changes, accounts, read state and persistence passed.');
