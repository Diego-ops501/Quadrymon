"use strict";
const assert = require("node:assert/strict");
const { create } = require("../src/domain/health-alerts");
const monitor = create();
const observe = (now, issues = ["idle"], live = true, key = "0:account") =>
  monitor.observe({ now, issues, live, key });
assert.deepEqual(observe(0, ["down"], false), []);
assert.deepEqual(observe(120000, ["down"], false), [], "login time does not consume the grace period");
assert.deepEqual(observe(130000), []);
assert.deepEqual(observe(189999), []);
assert.deepEqual(observe(190000), ["idle"]);
assert.deepEqual(observe(200000), [], "one notification while the issue continues");
assert.deepEqual(observe(201000, []), []);
assert.deepEqual(observe(202000), []);
assert.deepEqual(observe(231999), []);
assert.deepEqual(observe(232000), ["idle"], "recovery rearms only after another persistent issue");
assert.deepEqual(observe(240000, ["down"], false), []);
assert.deepEqual(observe(270000, ["down"], false), ["down"]);
assert.deepEqual(observe(280000), [], "reconnection gets a fresh grace period");
assert.deepEqual(observe(339999), []);
assert.deepEqual(observe(340000), ["idle"]);
assert.deepEqual(observe(350000, ["idle"], true, "1:account"), [], "reload resets observation");
assert.deepEqual(observe(410000, ["idle"], true, "1:account"), ["idle"]);
assert.deepEqual(observe(420000, ["idle"], true, "1:other"), [], "a new character gets a fresh observation period");
const transient = create();
assert.deepEqual(transient.observe({ key: "a", live: true, now: 0, issues: [] }), []);
assert.deepEqual(transient.observe({ key: "a", live: true, now: 59000, issues: ["faint"] }), []);
assert.deepEqual(transient.observe({ key: "a", live: true, now: 61000, issues: [] }), []);
assert.deepEqual(transient.observe({ key: "a", live: true, now: 100000, issues: [] }), []);
const accounts = Array.from({ length: 4 }, create);
for (const account of accounts) assert.deepEqual(account.observe({ key: "a", live: true, now: 0, issues: ["idle"] }), []);
assert.deepEqual(accounts[0].observe({ key: "a", live: true, now: 60000, issues: ["idle"] }), ["idle"]);
assert.deepEqual(accounts[1].observe({ key: "a", live: true, now: 60000, issues: [] }), []);
const disabled = create();
disabled.observe({ key: "a", live: true, now: 0, issues: ["idle"] });
assert.deepEqual(disabled.observe({ key: "a", live: true, now: 60000, issues: ["idle"], enabled: () => false }), []);
assert.deepEqual(disabled.observe({ key: "a", live: true, now: 61000, issues: ["idle"] }), ["idle"]);
console.log("Health alerts: startup, persistence, recovery, reconnect and account isolation passed.");
